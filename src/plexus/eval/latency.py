"""Cold latency and LLM usage per question: A6 vs A9 (Phase 5 gate: "with latency and cost").

    python -m plexus.eval.latency configs/a6_router.yaml configs/a9_agents.yaml

Cold = an EMPTY LLM cache for each config (a throwaway file), so every answer is really
generated by the local model; cached runs would only prove reproducibility, not speed.
30 dev questions (10 per type, seed 1). One untimed warm-up question per config loads the
models first; its time is reported separately. Cost is $0 (local model); reported as LLM
calls and tokens per question.
"""

from __future__ import annotations

import dataclasses
import json
import sys
import tempfile
import time
from pathlib import Path
from statistics import median

from plexus.settings import REPO_ROOT


def pct(xs: list[float], q: float) -> float:
    xs = sorted(xs)
    return round(xs[min(len(xs) - 1, int(q * len(xs)))], 1)


def run_config(path: Path, questions: list[dict]) -> dict:
    from plexus.agents.flow import ask, build_flow
    from plexus.baseline.naive import NaiveRAG
    from plexus.config import ExperimentConfig
    from plexus.llm import LLMClient
    from plexus.retrieve.pipeline import make_retriever
    from plexus.settings import Settings

    cfg = ExperimentConfig.load(path)
    with tempfile.TemporaryDirectory() as tmp:
        s = dataclasses.replace(
            Settings.load(), llm_cache_path=Path(tmp) / "cold.sqlite", llm_offline=False
        )
        llm = LLMClient.from_settings(s)
        t0 = time.perf_counter()
        retriever = make_retriever(cfg, s.data_dir)
        flow = build_flow(NaiveRAG(cfg, retriever, llm))
        ask(flow, "What risks does NVIDIA describe about export controls?")  # warm-up
        warm_ms = (time.perf_counter() - t0) * 1000
        llm.stats.calls = llm.stats.prompt_tokens = llm.stats.completion_tokens = 0
        totals, steps = [], {}
        try:
            for q in questions:
                t = time.perf_counter()
                _, trace = ask(flow, q["question"])
                totals.append((time.perf_counter() - t) * 1000)
                for st in trace:
                    steps.setdefault(st["step"], []).append(st["ms"])
        finally:
            if hasattr(retriever, "close"):
                retriever.close()
    n = len(questions)
    return {
        "config": cfg.name,
        "n": n,
        "warmup_ms_incl_model_load": round(warm_ms),
        "total_ms_p50": pct(totals, 0.5),
        "total_ms_p95": pct(totals, 0.95),
        "step_ms_median": {k: round(median(v), 1) for k, v in steps.items()},
        "llm_calls_per_question": round(llm.stats.calls / n, 2),
        "prompt_tokens_per_question": round(llm.stats.prompt_tokens / n),
        "completion_tokens_per_question": round(llm.stats.completion_tokens / n),
        "cost_usd": 0.0,
    }


def main(argv: list[str] | None = None) -> int:
    from plexus.eval.guardrails import attack_questions

    paths = [Path(p) for p in (argv if argv is not None else sys.argv[1:])]
    questions = attack_questions(REPO_ROOT / "data/golden/golden.jsonl", seed=1)
    out = [run_config(p, questions) for p in paths]
    dest = REPO_ROOT / "results" / ("latency_" + "_vs_".join(p.stem for p in paths) + ".json")
    dest.write_text(json.dumps(out, indent=2) + "\n")
    print(json.dumps(out, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
